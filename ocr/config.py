"""إعدادات الخدمة، كلها قابلة للتعديل عن طريق متغيرات البيئة (بادئة OCR_)."""

from __future__ import annotations

from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict

BASE_DIR = Path(__file__).resolve().parent.parent


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="OCR_", env_file=".env", extra="ignore")
    

    # اتصال Ollama
    ollama_url: str = "http://localhost:11434/api/generate"
    default_model: str = "qwen2.5vl:7b"
    request_timeout_seconds: float = 900

    # مدة إبقاء الموديل محمّل في الميموري بين الريكوستات. Ollama بيفضّي
    # الموديل تلقائيًا بعد فترة idle، وإعادة تحميله بتاخد دقايق طويلة على
    # CPU، فتثبيت القيمة دي مهم للسرعة.
    ollama_keep_alive: str = "30m"

    # لازم يفضل نفس الرقم بالظبط في كل نداء لـ Ollama بغض النظر عن الـ
    # endpoint. تغييره بين ريكوست وريكوست بيخلي Ollama يعيد تحميل الموديل
    # من الصفر حتى لو keep_alive شغّال.
    ollama_num_ctx: int = 16384

    # Ollama بيستخدم repeat_penalty=1.1 افتراضيًا. ده كارثي في الـ OCR: النصوص
    # النظامية بتكرر نفس الجملة عشرات المرات ("جزءاً في الألف من الذهب النقي")،
    # والعقوبة بتدفع الموديل يغيّر الكلمات عشان ميكررش - يعني بيرجّع نص مش
    # موجود في الصورة. 1.0 = العقوبة متوقفة تمامًا.
    ollama_repeat_penalty: float = 1.0

    # حدود حجم الصورة قبل ما تتبعت للموديل، وجودة ضغط الـ JPEG بعد الـ resize.
    # دقة أعلى = تعرّف أدق على الحروف المتشابهة في أسماء الأماكن/الأشخاص
    # (زي بريدة/بردة)، بس أبطأ شوية وبتاخد tokens أكتر - لذلك بنفرّق بين
    # استخراج الحقول (أسرع، أهم فيه سرعة) واستخراج النص الكامل (أهم فيه دقة).
    max_image_dimension: int = 1600
    max_image_dimension_text: int = 2400
    jpeg_quality: int = 95

    # الأفضل افتراضيًا إرسال الصفحة كاملة للموديل: التقطيع الآلي قد يفصل
    # العنوان عن قيمته، يغيّر ترتيب القراءة، ويحوّل الصفحة الواحدة إلى عدة
    # نداءات بطيئة. يمكن تفعيل الخيارين فقط لمجموعة مستندات ثبت أنها تحتاجهما.
    split_columns: bool = False

    # تقسيم أفقي اختياري للصور شديدة الكثافة. مغلق افتراضيًا للمحافظة على
    # السياق ولأن كل شريحة تضيف نداء Ollama كاملًا.
    split_bands: bool = False
    # عدد السطور في الشريحة الواحدة
    band_max_lines: int = 6

    # صفحات الـ PDF بتترسم على الـ DPI ده مباشرة بدل ما ترسم على dpi ثابت
    # وبعدين تتصغّر تاني (resample مرتين = فقدان حدة في الخط العربي الصغير).
    pdf_render_dpi: int = 300
    # سقف عدد صفحات الـ PDF اللي بتتعالج في الريكوست الواحد
    max_pdf_pages: int = 30
    # الفاصل اللي بيتحط بين صفحات الـ PDF في نتيجة /extract-all-text
    page_separator: str = "\n\n──────── صفحة {page} ────────\n\n"

    # أقصى عدد كلمات في حقل "موضوع"/"عنوان". فوق كده الموديل نقل الديباجة
    # أو متن المستند كله بدل سطر الموضوع - القيمة بتتلغى ويتسجّل تحذير،
    # لأن null أنضف من فقرة كاملة في حقل عنوان في Laserfiche.
    # 0 = اقفل الحارس.
    max_subject_words: int = 25

    # ── حراس الهلوسة ──────────────────────────────────────────────────────
    # ⚠ التلاتة دول كانوا ناقصين من الكونفج والكود بينده عليهم، فـ
    # extract_all_text كان بيرمي AttributeError من أول سطر، الـ endpoint
    # كان بيرجّع 500، والـ JS كان بيبلع الخطأ - ودي كانت مشكلة "الـ Text
    # pane مش بيتكتب".

    # القصاصة اللي شكلها زخرفة (طغراء، شعار، ختم، خط فاصل) متتبعتش للموديل
    # أصلًا. الموديل لما ميلاقيش نص مقروء مبيسكتش، بيملا الفراغ من ذاكرته.
    skip_decorative: bool = True

    # لو عدد سطور رد الموديل > عدد السطور المطبوعة في القصاصة × الرقم ده،
    # يبقى الرد فيه كلام مش موجود في الصورة والرد بيتلغى. ده الحارس الوحيد
    # اللي بيمسك التلوث الكامل (فقرة من مستند تاني خالص).
    max_line_inflation: float = 2.0
    # افتراضيًا نسجّل التحذير ولا نحذف النص: تقدير عدد السطور heuristic وقد
    # يخطئ مع الجداول والخط الصغير، وحذف رد صحيح أسوأ من إبقائه للمراجعة.
    line_inflation_log_only: bool = True

    # معالجة مدمّرة اختيارية. مغلقة افتراضيًا لأن العناوين الملونة قد تكون
    # محتوى حقيقيًا مطلوبًا، ولأن prompt يطلب من الموديل تجاهل الأختام.
    remove_color_ink: bool = False

    # أقصى عدد tokens في رد استخراج الحقول (JSON قصير عادة)
    fields_num_predict: int = 1024
    # أقصى عدد tokens في رد النص الكامل. مينفعش يبقى -1 (بلا حدود): لما
    # الموديل يدخل في لوب تكرار على صفحة كثيفة بيفضل يولّد بنود متخيلة لحد
    # ما التايم أوت يقطعه. السقف بيوقف اللوب ده.
    text_num_predict: int = 8192


    # التعامل مع سطور الخط الزخرفي المشكّل (ترويسة المراسيم).
    # "strip" = شيل الحركات وسيب الكلمات. الافتراضي "off" حتى يبقى all text
    # نسخة أمينة من رد OCR بلا حذف أو تعديل بعدي.
    # "drop"  = احذف السطر كله | "off" = اقفل الفلتر
    calligraphy_mode: str = "off"

    # كام سطر بكلمة واحدة ورا بعض في آخر الرد نعتبرهم prompt echo مفكوك.
    # ارفعه لـ 6 لو الفلتر ضرب على عمود كلمات حقيقي في فاتورة.
    echo_tail_min_run: int = 4
    
    # ── أمانة النص ────────────────────────────────────────────────────────
    # الافتراضي: /extract-all-text بيرجّع نص الموديل زي ما هو، بدون أي تعديل.
    # كل تحويل هنا بيعدّل النص المستخرج فعليًا، فكله متقفول افتراضيًا.

    # شيل التشكيل من النص الكامل. مغلق افتراضيًا لأن all text يجب أن يحافظ
    # على الحروف والحركات المطبوعة؛ يمكن تفعيله فقط لتطبيع فهرس البحث.
    strip_tashkeel_from_text: bool = False

    # مجلد حفظ ملفات النص المستخرج، نسبي لجذر المشروع لو مش absolute
    output_dir: Path = Path("extracted_texts")

    @property
    def resolved_output_dir(self) -> Path:
        return self.output_dir if self.output_dir.is_absolute() else BASE_DIR / self.output_dir


settings = Settings()
settings.resolved_output_dir.mkdir(parents=True, exist_ok=True)